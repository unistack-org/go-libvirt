// Front is the seam between the libvirt-RPC server and the hosting
// plane. A production implementation drives the real destination:
//
//	Prepare: create storage volumes from the guest XML disk list, open
//	         the RAM relay (a TCP splice toward the destination QEMU
//	         -incoming), bind a source-IP allowlist + TTL, persist a
//	         session record.
//	Finish:  resume (cancelled=false) or destroy (cancelled=true) the
//	         incoming domain.
type Front interface {
	// Prepare validates and stages the incoming migration. The returned
	// URIOut is the address the SOURCE QEMU connects to for guest RAM
	// (libvirt semantics: "IP:PORT"); optional side-channel endpoints
	// travel in CookieOut as a migration cookie.
	Prepare(ctx context.Context, req PrepareRequest) (PrepareResult, error)

	// Finish completes (cancelled=false) or rolls back (cancelled=true)
	// the staged migration.
	Finish(ctx context.Context, req FinishRequest) (FinishResult, error)

	// GetNodeInfo answers NODE_GET_INFO.
	GetNodeInfo() NodeInfo

	// Capabilities answers CONNECT_GET_CAPABILITIES (a minimal
	// domain_capabilities document is acceptable).
	Capabilities() (string, error)
}

// TokenValidator validates a SASL PLAIN credential presented by the
// source hypervisor. authzID/authcid/passwd are the three PLAIN fields;
// sourceIP is the peer address of the RPC connection. Returning an error
// fails authentication (the client sees only VIR_ERR_AUTH_FAILED).
type TokenValidator interface {
	Validate(authzID, authcid, passwd, sourceIP string) (Principal, error)
}

// Principal identifies the authenticated peer for the Front.
type Principal struct {
	ProjectID   string
	WindowID    string
	AllowNoAuth bool
}

// PrepareRequest carries everything Prepare3/Prepare3Params learned.
type PrepareRequest struct {
	Principal   Principal
	SourceIP    string // peer of the RPC connection; seeds the allowlist
	DomainName  string // dname override, empty → name from GuestXML
	Flags       uint64
	Bandwidth   uint64
	GuestXML    string
	Params      []TypedParamLite // only for the *3Params variant
	MigrationID string           // generated by the server; Finish uses it
}

// PrepareResult is what Prepare3 returns to the source.
type PrepareResult struct {
	URIOut    string // "IP:PORT" listenAddress for RAM
	CookieOut []byte // migration cookie, may be empty
}

// FinishRequest carries Finish3/Finish3Params data.
type FinishRequest struct {
	Principal   Principal
	SourceIP    string
	MigrationID string
	DomainName  string
	Cancelled   bool
	CookieIn    []byte
	Flags       uint64
	Params      []TypedParamLite
}

// FinishResult reports the final incoming state.
type FinishResult struct {
	// DomainUUID/DomainName identify the incoming guest for Finish ret.
	DomainUUID [16]byte
	DomainName string
}

// NodeInfo is the NODE_GET_INFO answer.
type NodeInfo struct {
	Model   string // e.g. "x86_64"
	Memory  uint64 // KiB
	CPUs    int32
	MHz     int32
	Nodes   int32
	Sockets int32
	Cores   int32
	Threads int32
}

// TypedParamLite is a flat view of a remote_typed_param for the Front.
type TypedParamLite struct {
	Field  string
	Kind   string // "int","uint","llong","ullong","double","boolean","string"
	Int    int64
	Float  float64
	String string
	Bool   bool
}

// GuestDisk is a disk target extracted from guest XML.
type GuestDisk struct {
	Type   string // file|block|network
	Device string // disk|lun
	Target string // vda...
	Format string // qcow2|raw...
}

// GuestDisks extracts target devices + backing info from guest XML.
func GuestDisks(guestXML string) ([]GuestDisk, error) {
	var dom struct {
		Name    string `xml:"name"`
		Devices struct {
			Disks []struct {
				Type   string `xml:"type,attr"`
				Device string `xml:"device,attr"`
				Target struct {
					Dev string `xml:"dev"`
				} `xml:"target"`
				Source struct {
					File   string `xml:"file,attr"`
					Dev    string `xml:"dev,attr"`
					Name   string `xml:"name,attr"`
					Format struct {
						Type string `xml:"type,attr"`
					} `xml:"format"`
					Protocol string `xml:"protocol,attr"`
				} `xml:"source"`
			} `xml:"devices>disk"`
		} `xml:"devices"`
	}
	if err := xml.Unmarshal([]byte(guestXML), &dom); err != nil {
		return nil, fmt.Errorf("libvirt: server: parse guest XML: %w", err)
	}
	var out []GuestDisk
	for _, d := range dom.Devices.Disks {
		if d.Device != "disk" && d.Device != "lun" {
			continue
		}
		out = append(out, GuestDisk{
			Type:   d.Type,
			Device: d.Device,
			Target: d.Target.Dev,
			Format: d.Source.Format.Type,
		})
	}
	return out, nil
}

// reHostdevPCI matches <hostdev ... type="pci" ...> with either quote style.
var reHostdevPCI = regexp.MustCompile(`(?s)<hostdev[^>]*type=['"]pci['"]`)

// ValidateGuestXML rejects configurations that cannot be faithfully
// staged on the receiving side: VFIO/PCI passthrough, shared-memory
// devices, hugetlbfs with prealloc="no", shared (share="on") file-backed
// disks, and internal snapshots.
func ValidateGuestXML(guestXML string) error {
	lower := strings.ToLower(guestXML)
	if !strings.Contains(lower, "<domain") {
		return fmt.Errorf("libvirt: server: not a domain XML document")
	}
	if reHostdevPCI.MatchString(lower) {
		return fmt.Errorf("libvirt: server: VFIO/PCI passthrough devices cannot be migrated in")
	}
	if strings.Contains(lower, "<shmem") {
		return fmt.Errorf("libvirt: server: shared memory devices cannot be migrated in")
	}
	if idx := strings.Index(lower, "<memorybacking"); idx >= 0 {
		if end := strings.Index(lower[idx:], "</memorybacking>"); end >= 0 {
			seg := lower[idx : idx+end]
			if strings.Contains(seg, "<hugepages") && strings.Contains(seg, "prealloc=\"no\"") {
				return fmt.Errorf("libvirt: server: hugepages with prealloc=no are not supported for incoming migration")
			}
		}
	}
	if strings.Contains(lower, "share=\"on\"") {
		return fmt.Errorf("libvirt: server: shared (share=on) file-backed disks are not supported for incoming migration")
	}
	// Internal snapshots: <domainsnapshot> is not part of migrate XML, so
	// this check fires only on XML that carries them; Prepare3 sees the
	// live domain XML.
	if strings.Contains(lower, "<snapshotsnapshot") || strings.Count(lower, "<snapshot ") > 0 {
		return fmt.Errorf("libvirt: server: internal snapshots are not supported for incoming migration")
	}
	return nil
}

// StubFront is an in-memory Front for tests and early wiring: it
// validates the guest XML, "stages" the migration (no volumes, no relay)
// and returns a configurable listen URI.
type StubFront struct {
	mu       sync.Mutex
	staged   map[string]*stubSession
	Node     NodeInfo
	CapsXML  string
	ListenIP string // IP to advertise in Prepare3 uriOut
}

type stubSession struct {
	name string
	done bool
}

// NewStubFront returns a test/development Front.
func NewStubFront(listenIP string) *StubFront {
	return &StubFront{
		staged:   make(map[string]*stubSession),
		ListenIP: listenIP,
		Node:     NodeInfo{Model: "x86_64", Memory: 8 * 1024 * 1024, CPUs: 4, MHz: 2500, Nodes: 1, Sockets: 1, Cores: 4, Threads: 1},
		CapsXML:  minimalCapabilitiesXML,
	}
}

// Prepare implements Front.
func (f *StubFront) Prepare(_ context.Context, req PrepareRequest) (PrepareResult, error) {
	if err := ValidateGuestXML(req.GuestXML); err != nil {
		return PrepareResult{}, err
	}
	name := req.DomainName
	if name == "" {
		var dom struct {
			Name string `xml:"name"`
		}
		_ = xml.Unmarshal([]byte(req.GuestXML), &dom)
		name = dom.Name
	}
	if name == "" {
		return PrepareResult{}, fmt.Errorf("libvirt: server: guest XML has no <name>")
	}
	f.mu.Lock()
	f.staged[req.MigrationID] = &stubSession{name: name}
	f.mu.Unlock()
	// Port 0 placeholder: the real front returns the RAM-relay port.
	return PrepareResult{URIOut: fmt.Sprintf("%s:0", f.ListenIP)}, nil
}

// Finish implements Front.
func (f *StubFront) Finish(_ context.Context, req FinishRequest) (FinishResult, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	s, ok := f.staged[req.MigrationID]
	if !ok {
		return FinishResult{}, fmt.Errorf("libvirt: server: unknown migration %s", req.MigrationID)
	}
	s.done = true
	if req.Cancelled {
		return FinishResult{DomainName: s.name}, nil
	}
	var uuid [16]byte
	copy(uuid[:], []byte(s.name)) // deterministic test UUID
	return FinishResult{DomainUUID: uuid, DomainName: s.name}, nil
}

// GetNodeInfo implements Front.
func (f *StubFront) GetNodeInfo() NodeInfo { return f.Node }

// Capabilities implements Front.
func (f *StubFront) Capabilities() (string, error) { return f.CapsXML, nil }

const minimalCapabilitiesXML = `<domain_capabilities check_supported="yes">
  <guest>
    <os_type>hvm</os_type>
    <arch name="x86_64">
      <wordsize>64</wordsize>
      <domain type="kvm">
        <machine>pc-q35-8.2</machine>
        <machine canonical="pc-q35-8.2">pc-q35-8.2</machine>
        <machine>pc-i440fx-8.2</machine>
        <binary>/usr/bin/qemu-system-x86_64</binary>
      </domain>
    </arch>
  </guest>
</domain_capabilities>`
